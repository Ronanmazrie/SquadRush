        public static void ImportTextResources()
        {
            if (!Application.isBatchMode) throw new InvalidOperationException("Use the setup script to import text resources.");
            if (Shader.Find("TextMeshPro/Mobile/Distance Field") != null) { EditorApplication.Exit(0); return; }
            // Replace only the empty settings generated by the previous incomplete setup.
            var oldSettings = AssetDatabase.LoadAssetAtPath<TMP_Settings>("Assets/Resources/TMP Settings.asset");
            if (oldSettings != null && Resources.Load<TMP_FontAsset>("SquadFont") == null)
                AssetDatabase.DeleteAsset("Assets/Resources/TMP Settings.asset");
            AssetDatabase.importPackageCompleted += TextResourcesImported;
            AssetDatabase.importPackageFailed += TextResourcesFailed;
            importDeadline = EditorApplication.timeSinceStartup + 180;
            EditorApplication.update += WatchImport;
            TMP_PackageResourceImporter.ImportResources(true, false, false);
        }
        static void WatchImport()
        {
            if (EditorApplication.timeSinceStartup <= importDeadline) return;
            Debug.LogError("[SquadRush] Text resource import timed out."); EditorApplication.Exit(1);
        }
        static void TextResourcesImported(string packageName)
        {
            if (packageName != "TMP Essential Resources") return;
            EditorApplication.update -= WatchImport;
            AssetDatabase.SaveAssets(); Debug.Log("[SquadRush] Text resources imported."); EditorApplication.Exit(0);
        }
        static void TextResourcesFailed(string packageName, string error)
        { Debug.LogError("[SquadRush] Text resource import failed: " + error); EditorApplication.Exit(1); }

