        public static void PrepareVisuals()
        {
            EnsureStageGlyphs();
            // Runtime-created materials need serialized representatives so build stripping retains instancing.
            CreateSeed("SquadToon", "SquadRush/Toon");
            CreateSeed("SquadGlow", "SquadRush/Glow");
            var graphics = new SerializedObject(AssetDatabase.LoadAllAssetsAtPath("ProjectSettings/GraphicsSettings.asset")[0]);
            graphics.FindProperty("m_FogStripping").intValue = 1; // Custom: fog is enabled by runtime scene construction.
            graphics.FindProperty("m_FogKeepLinear").boolValue = true;
            graphics.FindProperty("m_FogKeepExp").boolValue = false;
            graphics.FindProperty("m_FogKeepExp2").boolValue = false;
            graphics.ApplyModifiedPropertiesWithoutUndo();
            const string path = "Assets/Resources/SquadValue.mat";
            var material = AssetDatabase.LoadAssetAtPath<Material>(path);
            if (material == null)
            {
                material = new Material(Resources.Load<TMP_FontAsset>("SquadFont").material) { name = "SquadValue" };
                AssetDatabase.CreateAsset(material, path);
            }
            material.SetColor("_OutlineColor", new Color(0.025f, 0.04f, 0.07f));
            material.SetFloat("_OutlineWidth", 0.22f); material.EnableKeyword("OUTLINE_ON");
            EditorUtility.SetDirty(material); AssetDatabase.SaveAssets();
        }
        static void EnsureStageGlyphs()
        {
            var font = Resources.Load<TMP_FontAsset>("SquadFont");
            if (font == null) throw new InvalidOperationException("Generate the prototype font first.");
            string characters = "";
            foreach (string file in Directory.GetFiles(Path.Combine(Application.dataPath, "Scripts"), "*.cs", SearchOption.AllDirectories)) characters += File.ReadAllText(file);
            characters = new string(characters.Where(c => c >= 32 && !char.IsSurrogate(c) && !font.HasCharacter(c)).Distinct().ToArray());
            if (characters.Length == 0) return;
            font.atlasPopulationMode = AtlasPopulationMode.Dynamic;
            // TMP drops the runtime source reference for a saved static atlas; restore it only while baking.
            var serializedFont = new SerializedObject(font);
            serializedFont.FindProperty("m_SourceFontFile").objectReferenceValue = AssetDatabase.LoadAssetAtPath<Font>("Assets/Fonts/NotoSansCJKjp-Regular.otf");
            serializedFont.ApplyModifiedPropertiesWithoutUndo();
            try
            {
                if (!font.TryAddCharacters(characters, out string missing) && !string.IsNullOrEmpty(missing))
                    throw new InvalidOperationException("Font atlas is missing stage text: " + missing);
            }
            finally { font.atlasPopulationMode = AtlasPopulationMode.Static; }
            EditorUtility.SetDirty(font);
            foreach (var texture in font.atlasTextures) { if (!AssetDatabase.Contains(texture)) AssetDatabase.AddObjectToAsset(texture, font); EditorUtility.SetDirty(texture); }
        }
        static void CreateSeed(string name, string shaderName)
        {
            string path = "Assets/Resources/" + name + ".mat";
            if (AssetDatabase.LoadAssetAtPath<Material>(path) != null) return;
            Shader shader = Shader.Find(shaderName);
            if (shader == null) throw new InvalidOperationException("Required shader missing: " + shaderName);
            AssetDatabase.CreateAsset(new Material(shader) { name = name, enableInstancing = true }, path);
        }
        static void CreateFont()
        {
            const string fontPath = "Assets/Resources/SquadFont.asset";
            if (AssetDatabase.LoadAssetAtPath<TMP_FontAsset>(fontPath) != null) return;
            if (Shader.Find("TextMeshPro/Mobile/Distance Field") == null)
                throw new InvalidOperationException("Run Initialize-Prototype.ps1 to import TMP Essential Resources first.");
            var tmpSettings = Resources.Load<TMP_Settings>("TMP Settings");
            if (tmpSettings == null)
            {
                tmpSettings = ScriptableObject.CreateInstance<TMP_Settings>();
                AssetDatabase.CreateAsset(tmpSettings, "Assets/Resources/TMP Settings.asset");
            }
            Font source = AssetDatabase.LoadAssetAtPath<Font>("Assets/Fonts/NotoSansCJKjp-Regular.otf");
            if (source == null) throw new InvalidOperationException("Japanese font has not been imported.");
            TMP_FontAsset font = TMP_FontAsset.CreateFontAsset(source, 48, 5, GlyphRenderMode.SDFAA, 1024, 1024, TMPro.AtlasPopulationMode.Dynamic, false);
            if (font == null) throw new InvalidOperationException("Could not create Japanese font atlas.");
            string characters = new string(Enumerable.Range(32, 95).Select(n => (char)n).ToArray()) + "×←→Ⅱ";
            foreach (string file in Directory.GetFiles(Path.Combine(Application.dataPath, "Scripts"), "*.cs", SearchOption.AllDirectories)) characters += File.ReadAllText(file);
            characters = new string(characters.Where(c => c >= 32 && !char.IsSurrogate(c)).Distinct().ToArray());
            if (!font.TryAddCharacters(characters, out string missing) && !string.IsNullOrEmpty(missing))
                throw new InvalidOperationException("Font atlas is missing characters: " + missing);
            font.atlasPopulationMode = TMPro.AtlasPopulationMode.Static;
            font.name = "SquadFont";
            AssetDatabase.CreateAsset(font, fontPath);
            AssetDatabase.AddObjectToAsset(font.material, font);
            foreach (Texture2D atlas in font.atlasTextures) AssetDatabase.AddObjectToAsset(atlas, font);
            var serializedSettings = new SerializedObject(tmpSettings);
            SerializedProperty defaultFont = serializedSettings.FindProperty("m_defaultFontAsset");
            if (defaultFont != null) { defaultFont.objectReferenceValue = font; serializedSettings.ApplyModifiedPropertiesWithoutUndo(); }
            EditorUtility.SetDirty(font); AssetDatabase.SaveAssets();
        }

        [MenuItem("Squad Rush/Verify Gameplay Scenarios")]
        public static void Verify()
        {
            PrepareVisuals();
            if (EditorApplication.isPlaying) throw new InvalidOperationException("Stop Play mode before verifying.");
            if (Resources.Load<TMP_FontAsset>("SquadFont") == null) throw new InvalidOperationException("Generate the prototype first.");
            var checks = new System.Collections.Generic.List<string>();
            string storageKey = "SquadRush.Verification." + Guid.NewGuid();
            var root = new GameObject("VerificationOnly");
            try
            {
                var game = root.AddComponent<SquadRushGame>(); game.Initialize();
                game.ConfigureVerification(storageKey);
                Expect(game.State == RunState.Ready && game.SquadCount == 3, "Initial menu", checks);
                Expect(game.Hud.CurrentPage == FrontEndPage.Home && game.Equipment.OwnedCount == 0, "New profile opens Home without unearned equipment", checks);
                game.OpenStages(); game.SelectStage(999);
                Expect(game.Hud.CurrentPage == FrontEndPage.Stages && game.StageNumber == 1, "Stage selection restricts play to unlocked stages", checks);
                game.OpenGacha(); game.Tick(1, false);
                Expect(game.Hud.CurrentPage == FrontEndPage.Gacha && game.Equipment.OwnedCount == 0 && game.Elapsed == 0, "Gacha is a non-playing placeholder with no rewards", checks);
                game.OpenEquipment(); game.ToggleEquipment(0);
                Expect(game.Equipment.WeaponPower == 0 && !game.Equipment.IsEquipped(0), "Unowned gear cannot be equipped", checks);
                game.Begin(); game.Tick(0.2f, false);
                Expect(Mathf.Abs(game.GroundTravel - 0.7f) < 0.001f && Mathf.Abs(GroundOffset(game, "RoadSurface") - 0.2f) < 0.001f && Mathf.Abs(GroundOffset(game, "SoilSurface") - 0.12f) < 0.001f && Mathf.Abs(GroundOffset(game, "CurbSurface") - 0.18f) < 0.001f, "Road, soil and curb texture features all scroll backward at 3.5 metres per second", checks);
                var ground = game.transform.Find("World/RoadSurface").GetComponent<MeshFilter>().sharedMesh;
                Expect(ground.vertices[1].z > ground.vertices[0].z && ground.uv[1].y > ground.uv[0].y, "Ground UV orientation matches forward world distance", checks);
                game.TogglePause(); game.Tick(1, false);
                Expect(Mathf.Abs(game.GroundTravel - 0.7f) < 0.001f && Mathf.Abs(GroundOffset(game, "SoilSurface") - 0.12f) < 0.001f, "Pause freezes both terrain distance and visible texture offset", checks);
                game.Begin(); Expect(game.GroundTravel == 0 && GroundOffset(game, "RoadSurface") == 0, "Retry resets terrain phase", checks);
                game.ChangeSquad(997);
                for (int i = 0; i < 1050; i++) game.Tick(0.02f, false);
                Expect(game.State == RunState.Playing && Mathf.Abs(game.GroundTravel - 3.5f) < 0.02f && GroundOffset(game, "SoilSurface") >= 0 && GroundOffset(game, "SoilSurface") < 1, "Ground scrolling wraps after 70 metres without growing UV values", checks);
                game.ShowHome(); game.Tick(1, false);
                Expect(game.State == RunState.Ready && game.GroundTravel == 0 && game.Hud.CurrentPage == FrontEndPage.Home && game.ActiveTargets == 0, "Returning Home clears combat and freezes the field", checks);
                game.Begin(); game.ApplyGate(5, false); game.ApplyGate(2, true); game.ApplyGate(-4, false);
                Expect(game.SquadCount == 12, "Addition, multiplication and subtraction gates", checks);
                game.ChangeSquad(100); Expect(game.SquadCount == 112, "Squad grows beyond the old 60-ally cap", checks);
                game.ChangeSquad(887); Expect(game.SquadCount == 999, "Squad counts 999 allies exactly", checks);
                game.ApplyGate(2, true); Expect(game.SquadCount == 1000, "Multiplication clamps at 1000 allies", checks);
                game.ChangeSquad(-1); Expect(game.SquadCount == 999, "Loss below the 1000 cap remains exact", checks);
                game.ChangeSquad(2000); game.Tick(0.02f, false);
                Expect(game.VisibleAllies == 96 && game.ActiveBullets == 40 && game.LastVolleyDamage == 1000, "1000 allies contribute full volley damage with bounded actors and tracers", checks);
                game.SpawnTarget(TargetKind.Enemy, 0, 8, 20);
                for (int i = 0; i < 25; i++) game.Tick(0.02f, false);
                Expect(game.Kills == 1, "Aggregated projectiles apply real damage to a 20-health enemy", checks);
                game.SpawnTarget(TargetKind.Enemy, 0, 1.6f, 9999); game.Tick(0.02f, false);
                Expect(game.SquadCount == 999, "Contact at 1000 allies removes exactly one ally", checks);
                for (int i = 0; i < 200; i++) game.Tick(0.02f, false);
                Expect(game.ActiveBullets <= 384 && game.VisibleAllies <= 96, "Sustained large-squad combat stays within fixed pools", checks);
                game.ChangeSquad(-10000); Expect(game.State == RunState.Lost, "Zero allies ends the run", checks);
                game.Begin(); Expect(game.State == RunState.Playing && game.SquadCount == 3 && game.ActiveTargets == 0 && game.ActiveBullets == 0, "Retry clears the run", checks);
                game.TogglePause(); float time = game.Elapsed; game.Tick(1, false);
                Expect(game.State == RunState.Paused && game.Elapsed == time, "Pause freezes simulation", checks);
                game.MenuAction(); Expect(game.State == RunState.Playing, "Resume", checks);
