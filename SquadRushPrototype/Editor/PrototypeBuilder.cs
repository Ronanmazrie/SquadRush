                Expect(game.SquadCount == game.Stage.StartingAllies + 2 && game.WeaponDamage == 2 && Mathf.Abs(game.FireRateMultiplier - 1.1f) < 0.001f, "Weapon, armor and support bonuses apply together at sortie", checks);
